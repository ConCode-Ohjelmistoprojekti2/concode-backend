/* SQL script used to create the leaderboard table and indexes for the project database.*/
CREATE TABLE IF NOT EXISTS scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_name VARCHAR(30) NOT NULL,
    score INTEGER NOT NULL CHECK (score >= 0),
    mode VARCHAR(10) NOT NULL CHECK (mode IN ('DAILY', 'RANDOM')),
    challenge_date DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS scores_daily_leaderboard_idx
    ON scores (mode, challenge_date, score DESC, created_at ASC);

CREATE INDEX IF NOT EXISTS scores_random_leaderboard_idx
    ON scores (mode, score DESC, created_at ASC);
