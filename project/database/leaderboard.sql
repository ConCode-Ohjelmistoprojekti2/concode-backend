/* SQL script used to create the leaderboard table and indexes for the project database.*/
CREATE TABLE IF NOT EXISTS scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_name VARCHAR(30) NOT NULL,
    score NUMERIC(10, 2) NOT NULL CHECK (score >= 0),
    mode VARCHAR(10) NOT NULL CHECK (mode IN ('DAILY', 'RANDOM')),
    challenge_date DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS scores_daily_leaderboard_idx
    ON scores (mode, challenge_date, score DESC, created_at ASC);

CREATE INDEX IF NOT EXISTS scores_random_leaderboard_idx
    ON scores (mode, score DESC, created_at ASC);


CREATE TABLE IF NOT EXISTS profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    username VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS profiles_username_lower_unique
    ON profiles (LOWER(username));

ALTER TABLE scores ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE;

ALTER TABLE scores
    ALTER COLUMN score TYPE NUMERIC(10, 2)
    USING score::NUMERIC(10, 2);

CREATE UNIQUE INDEX IF NOT EXISTS scores_one_run_per_user_per_day_idx
    ON scores (user_id, mode, challenge_date)
    WHERE user_id IS NOT NULL;
